"""
GemmaBrowserAgent - doc_scraper.py
====================================
Specialized agent: Automated Documentation Scraper & Summarizer

Given a documentation URL, this agent:
  1. Visits the site and extracts the navigation structure
  2. Crawls key pages and captures text + screenshot snapshots
  3. Asks Gemma/Gemini to produce a structured Markdown summary
  4. Saves the output to output/docs_summary_<domain>_<timestamp>.md

Usage:
    uv run doc_scraper.py
    DOC_URL=https://docs.fastapi.tiangolo.com uv run doc_scraper.py

Requirements (.env):
    GEMINI_API_KEY=your-key
"""

from __future__ import annotations

import asyncio
import os
import re
from datetime import datetime
from pathlib import Path
from urllib.parse import urlparse

from dotenv import load_dotenv

from browser_use import Agent
from browser_use.llm.google import ChatGoogle

load_dotenv()

API_KEY: str | None = os.getenv("GEMINI_API_KEY") or os.getenv("GOOGLE_API_KEY")
MODEL_ID: str = os.getenv("GEMMA_MODEL", "gemini-2.5-flash")
DOC_URL: str = os.getenv("DOC_URL", "https://docs.browser-use.com")
MAX_PAGES: int = int(os.getenv("MAX_PAGES", "5"))
OUTPUT_DIR: Path = Path(os.getenv("OUTPUT_DIR", "./output"))

if not API_KEY:
    raise EnvironmentError(
        "GEMINI_API_KEY not set. Get one at https://aistudio.google.com/app/apikey"
    )


def _slug(url: str) -> str:
    domain = urlparse(url).netloc.replace(".", "_")
    return re.sub(r"[^\w]", "_", domain)


def _output_path(url: str) -> Path:
    slug = _slug(url)
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    return OUTPUT_DIR / f"docs_summary_{slug}_{timestamp}.md"


def build_task(url: str, max_pages: int) -> str:
    return f"""You are a technical documentation researcher with vision capabilities.

Your goal: visit {url} and produce a comprehensive, structured Markdown summary.

Steps:
1. Open the documentation homepage at {url}.
2. Identify the main navigation sections / table-of-contents.
3. Visit up to {max_pages} of the most important pages (Getting Started,
   Installation, API Reference, Examples, Configuration).
4. For each page you visit:
   - Extract the page title
   - Extract the core concepts explained (2-4 bullet points)
   - Note any code snippets or commands shown
5. After visiting all pages, produce a single Markdown document with:
   - A title "# Documentation Summary: <site name>"
   - A "## Overview" section (2-3 sentences about the project)
   - A "## Key Sections" section listing each page visited with title, URL, and bullet-point summary
   - A "## Quick-Start Commands" section with the most important installation/usage commands found
   - A "## Key Concepts" section summarising the most important ideas
6. Return ONLY the Markdown document as your final answer.

Important: Use your visual ability to read the actual page content (text + screenshots).
"""


async def main() -> None:
    llm = ChatGoogle(
        model=MODEL_ID,
        api_key=API_KEY,
        temperature=0.2,
        max_output_tokens=8192,
    )

    task = build_task(DOC_URL, MAX_PAGES)

    print(f"\n GemmaBrowserAgent - Documentation Scraper")
    print(f"   Target : {DOC_URL}")
    print(f"   Model  : {MODEL_ID}")
    print(f"   Pages  : up to {MAX_PAGES}\n")

    agent = Agent(task=task, llm=llm)
    result = await agent.run()

    out_path = _output_path(DOC_URL)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    markdown_content = str(result)

    with open(out_path, "w", encoding="utf-8") as f:
        f.write(f"<!-- Generated by GemmaBrowserAgent on {datetime.now().isoformat()} -->\n\n")
        f.write(markdown_content)

    print(f"\n Summary saved to: {out_path}")
    print("\n--- PREVIEW (first 800 chars) ---")
    print(markdown_content[:800])
    print("...")


if __name__ == "__main__":
    asyncio.run(main())
